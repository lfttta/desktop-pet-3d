"""Regenerate the minimal vendored ABI from the authorized Godot executable.

The Object.notification hash and engine version are derived from the engine's
own extension_api.json and written to vendor/godot/pet_abi.h; the C++ binding
includes that header instead of hardcoding a hash. A version mismatch aborts
loudly, and a changed hash is reported so the DLL is rebuilt deliberately.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import shutil
import subprocess

NATIVE = Path(__file__).resolve().parent
EXPECTED_VERSION = (4, 7, 2)
parser = argparse.ArgumentParser()
parser.add_argument("--godot", default=os.environ.get("PET3D_ENGINE") or
                    r"D:\danjigame\GODDOT  WORD\Godot_v4.7.2-stable_win64.exe")
args = parser.parse_args()
work = NATIVE / "build/abi"
work.mkdir(parents=True, exist_ok=True)
result = subprocess.run([args.godot, "--headless", "--dump-gdextension-interface", "--dump-extension-api"],
    cwd=work, capture_output=True, timeout=60)
if result.returncode:
    raise SystemExit(result.stderr.decode("utf-8", errors="replace"))
data = json.loads((work / "extension_api.json").read_text(encoding="utf-8"))
header = data["header"]
version = (header["version_major"], header["version_minor"], header["version_patch"])
if version != EXPECTED_VERSION:
    raise SystemExit(
        f"ENGINE MISMATCH: dump came from Godot {'.'.join(map(str, version))}, but the vendored ABI "
        f"pins {'.'.join(map(str, EXPECTED_VERSION))}. Update EXPECTED_VERSION and re-verify the "
        "binding deliberately; refusing to replace the ABI silently.")
sizes = next(b for b in data["builtin_class_sizes"] if b["build_configuration"] == "float_64")
selected = {s["name"]: s["size"] for s in sizes["sizes"] if s["name"] in ("String", "StringName", "Vector2i")}
assert selected == {"String": 8, "Vector2i": 8, "StringName": 8}, selected
notification = next(m for c in data["classes"] if c["name"] == "Object"
    for m in c["methods"] if m["name"] == "notification")
notification_hash = notification["hash"]
vendor = NATIVE / "vendor/godot"
vendor.mkdir(parents=True, exist_ok=True)
shutil.copy2(work / "gdextension_interface.h", vendor)
# Derive the constants the C++ binding compiles against; never hardcode a hash.
constants = (
    "// Generated by native/refresh_abi.py from the engine's extension_api.json.\n"
    "// Do not edit by hand; rerun the script with the authorized engine instead.\n"
    "#pragma once\n"
    f"#define PET_GODOT_VERSION_MAJOR {version[0]}\n"
    f"#define PET_GODOT_VERSION_MINOR {version[1]}\n"
    f"#define PET_GODOT_VERSION_PATCH {version[2]}\n"
    f"#define PET_OBJECT_NOTIFICATION_HASH {notification_hash}ULL\n"
)
constants_path = vendor / "pet_abi.h"
previous = constants_path.read_text(encoding="utf-8") if constants_path.is_file() else ""
if previous and previous != constants:
    print("ABI CONSTANTS CHANGED: Object.notification hash or engine version differs from the "
          "previous vendored header; rebuild the native DLL before running the app.")
constants_path.write_text(constants, encoding="utf-8", newline="\n")
manifest = {"engine": header, "engine_stdout": result.stdout.decode("utf-8", errors="replace").strip(),
    "source": "Generated by the user's official Godot 4.7.2 executable; no downloaded bindings",
    "upstream": "https://github.com/godotengine/godot",
    "sizes_float_64": selected, "Object.notification": notification,
    "header_sha256": hashlib.sha256((vendor / "gdextension_interface.h").read_bytes()).hexdigest(),
    "constants_sha256": hashlib.sha256(constants_path.read_bytes()).hexdigest()}
(vendor / "abi.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"Refreshed Godot {'.'.join(map(str, version))} ABI header, pet_abi.h "
      f"(Object.notification hash={notification_hash}) and metadata; full API dump stays in native/build/abi")
